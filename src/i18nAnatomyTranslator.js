export function toTraditionalChinese(str) {
  if (!str) return '';
  let out = String(str);
  for (const [simp, trad] of SIMP_TO_TRAD_PHRASES) {
    if (out.includes(simp)) out = out.split(simp).join(trad);
  }
  let res = '';
  for (const ch of out) {
    res += SIMP_TO_TRAD_CHARS[ch] || ch;
  }
  return res;
}

function capFirst(s) {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Translate any anatomical structure or group name from English into `en`, `es`, `zh`, `yue`, `ja`, `ko`, `pt`, `fr`, or `it`.
 */
export function translateAnatomyName(englishName, lang = 'en') {
  if (!englishName || lang === 'en') return englishName || '';
  const cache = translationCache[lang];
  if (cache && cache.has(englishName)) return cache.get(englishName);

  const lower = englishName.trim().toLowerCase();
  if (EXACT_NAMES[lower] && EXACT_NAMES[lower][lang]) {
    const res = EXACT_NAMES[lower][lang];
    if (cache) cache.set(englishName, res);
    return res;
  }

  let out = null;
  if (lang === 'es') {
    out = translateToSpanish(lower, englishName);
  } else if (lang === 'zh') {
    out = translateToChinese(lower, englishName);
  } else if (lang === 'yue') {
    const zhOut =
      EXACT_NAMES[lower] && EXACT_NAMES[lower].zh
        ? EXACT_NAMES[lower].zh
        : translateToChinese(lower, englishName);
    out = toTraditionalChinese(zhOut);
  } else if (lang === 'ja' || lang === 'ko' || lang === 'pt' || lang === 'fr' || lang === 'it') {
    out = translateExtraLang(lower, englishName, lang);
  } else {
    out = englishName;
  }

  if (cache) cache.set(englishName, out);
  return out;
}

