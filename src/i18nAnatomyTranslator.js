function translateToSpanish(lower, original) {
  // Handle "X of left/right Y" e.g. "Long head of left biceps brachii", "Abdominal part of right pectoralis major"
  const ofMatch = lower.match(/^(.+?)\s+of\s+(left\s+|right\s+)?(.+)$/);
  if (ofMatch) {
    const [, prefix, sideRaw, rest] = ofMatch;
    const prefixEs = translateFragmentEs(prefix.trim());
    const restEs = translateFragmentEs(rest.trim());
    const isRestFem = /^(arteria|vena|costilla|vértebra|glándula|trompa|rama|tributaria|porción|cabeza|escápula|clavícula|rótula|tibia|fíbula|ulna|mano|falange)/i.test(restEs);
    const sideEs = sideRaw
      ? sideRaw.trim() === 'left'
        ? isRestFem ? 'izquierda' : 'izquierdo'
        : isRestFem ? 'derecha' : 'derecho'
      : '';
    return capFirst(`${prefixEs} de ${restEs}${sideEs ? ' ' + sideEs : ''}`);
  }

  // Handle leading "left X" or "right X"
  const sideMatch = lower.match(/^(left|right)\s+(.+)$/);
  if (sideMatch) {
    const [, side, rest] = sideMatch;
    const restEs = translateFragmentEs(rest.trim());
    const isFem = /^(arteria|vena|costilla|vértebra|glándula|trompa|rama|tributaria|porción|cabeza|escápula|clavícula|rótula|tibia|fíbula|ulna|mano|falange)/i.test(restEs);
    const sideWord = side === 'left' ? (isFem ? 'izquierda' : 'izquierdo') : (isFem ? 'derecha' : 'derecho');
    return capFirst(`${restEs} ${sideWord}`);
  }

  const frag = translateFragmentEs(lower);
  return frag ? capFirst(frag) : original;
}

function translateFragmentEs(s) {
  if (HEAD_PHRASES_ES[s]) return HEAD_PHRASES_ES[s];
  if (EXACT_NAMES[s] && EXACT_NAMES[s].es) return EXACT_NAMES[s].es.toLowerCase();
  for (const [en, es] of TERM_STEMS) {
    if (s === en) return es;
  }
  let working = s;
  for (const [en, es] of Object.entries(HEAD_PHRASES_ES)) {
    if (working.includes(en)) working = working.replace(en, es);
  }
  for (const [en, es] of TERM_STEMS) {
    if (working.includes(en)) {
      working = working.replace(en, es);
    }
  }
  const isFem = /(costilla|vértebra|falange|arteria|vena|rama|tributaria|porción|cabeza|mano)/i.test(working);
  // Ordinal + noun (e.g. "first rib", "fifth lumbar vertebra", "first lumbrical")
  for (const [ordEn, ordObj] of Object.entries(ORDINALS)) {
    const re = new RegExp(`\\b${ordEn}\\b`, 'g');
    if (re.test(working)) {
      working = working.replace(re, isFem ? ordObj.esFem : ordObj.esMasc);
    }
  }
  // Replace common modifiers if still in English
  if (working === s) {
    const tokens = working.split(/\s+/);
    if (tokens.length >= 2) {
      const last = tokens[tokens.length - 1];
      if (
        last === 'artery' ||
        last === 'vein' ||
        last === 'nerve' ||
        last === 'muscle' ||
        last === 'bone' ||
        last === 'ligament' ||
        last === 'tendon' ||
        last === 'gland' ||
        last === 'duct' ||
        last === 'lobe' ||
        last === 'branch' ||
        last === 'tributary' ||
        last === 'trunk' ||
        last === 'plexus' ||
        last === 'sinus' ||
        last === 'head' ||
        last === 'part'
      ) {
        const headEs = WORD_MAP_ES[last] || last;
        const headIsFem = /^(arteria|vena|glándula|rama|tributaria|cabeza|porción)$/i.test(headEs);
        const mods = tokens
          .slice(0, -1)
          .map((t) => {
            const m = WORD_MAP_ES[t] || t;
            if (headIsFem && m.endsWith('o')) return m.slice(0, -1) + 'a';
            return m;
          })
          .join(' ');
        return `${headEs} ${mods}`;
      }
    }
  }
  return working;
}

function translateToChinese(lower, original) {
  // Handle "X of left/right Y"
  const ofMatch = lower.match(/^(.+?)\s+of\s+(left|right\s+)?(.+)$/);
  if (ofMatch) {
    const [, prefix, sideRaw, rest] = ofMatch;
    const sideZh = sideRaw ? (sideRaw.trim() === 'left' ? '左' : '右') : '';
    const restZh = translateFragmentZh(rest.trim());
    const prefixZh = translateFragmentZh(prefix.trim());
    return `${sideZh}${restZh}${prefixZh}`;
  }

  // Handle leading "left X" or "right X"
  const sideMatch = lower.match(/^(left|right)\s+(.+)$/);
  if (sideMatch) {
    const [, side, rest] = sideMatch;
    const sideZh = side === 'left' ? '左' : '右';
    const restZh = translateFragmentZh(rest.trim());
    return `${sideZh}${restZh}`;
  }

  return translateFragmentZh(lower) || original;
}

function translateFragmentZh(s) {
  if (EXACT_NAMES[s] && EXACT_NAMES[s].zh) return EXACT_NAMES[s].zh;
  for (const [en, , zh] of TERM_STEMS) {
    if (s === en) return zh;
  }
  let working = s;
  let replacedAny = false;
  for (const [en, , zh] of TERM_STEMS) {
    if (working.includes(en)) {
      working = working.replace(en, zh);
      replacedAny = true;
    }
  }
  for (const [ordEn, ordObj] of Object.entries(ORDINALS)) {
    const re = new RegExp(`\\b${ordEn}\\b`, 'g');
    if (re.test(working)) {
      working = working.replace(re, ordObj.zh);
      replacedAny = true;
    }
  }
  const tokens = working.split(/\s+/);
  const mappedTokens = tokens.map((t) => {
    const clean = t.replace(/[^a-z]/g, '');
    if (WORD_MAP_ZH[clean]) {
      replacedAny = true;
      return WORD_MAP_ZH[clean];
    }
    return t;
  });
  if (replacedAny) {
    // Join Chinese characters without spaces while keeping any remaining Latin/numbers spaced
    return mappedTokens.join('').replace(/([\u4e00-\u9fa5])\s+([\u4e00-\u9fa5])/g, '$1$2');
  }
  return working;
}

